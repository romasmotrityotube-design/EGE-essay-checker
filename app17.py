import json
import requests
import streamlit as st

# Настройка страницы в браузере
st.set_page_config(
    page_title="ЕГЭ ИИ-Ассистент (Яндекс Алиса AI)", page_icon="📝", layout="centered"
)

# Безопасное получение ключей из секретов (код не знает сами значения, он берет их по названию)
API_KEY = st.secrets["YANDEX_API_KEY"]
FOLDER_ID = st.secrets["YANDEX_FOLDER_ID"]

# ============================================================
#  ШАГ 1. БЕСПРИСТРАСТНЫЙ СИСТЕМНЫЙ ПРОМПТ С ЖЕСТКИМИ ТРИГГЕРАМИ
# ============================================================
SYSTEM_PROMPT = """
Ты — профессиональный, хладнокровный и абсолютно беспристрастный эксперт ФИПИ по проверке сочинений ЕГЭ (задание 27). 
Твоя задача — не хвалить ученика, а проводить жесткий аудит структуры текста по критериям 2027 года (максимум — 22 балла). Отвечай ТОЛЬКО на русском языке.

ЖЕСТКИЕ ПРАВИЛА ОБНУЛЕНИЯ КРИТЕРИЕВ:
- К4 (Обоснование): Ставь 1 балл ТОЛЬКО если в тексте есть четко выраженное отношение (согласие/несогласие), тезис И конкретный развернутый аргумент (из литературы, истории, личного опыта или искусства). Если аргумента нет вообще, или приведена просто пустая фраза без доказательства — ты ОБЯЗАН поставить СТРОГО 0 баллов. Не додумывай аргументы за ученика!
- К2 (Комментарий): Если ученик не приводит конкретных примеров-иллюстраций из текста, этот критерий безжалостно режется до 0-1 балла.

СЕТКА СНИЖЕНИЯ БАЛЛОВ ЗА ГРАМОТНОСТЬ (К7–К10):
- К7 (Орфография): 3 балла — 0 ошибок; 2 балла — 1-2 ошибки; 1 балл — 3-4 ошибки; 0 баллов — 5+ ошибок.
- К8 (Пунктуация): 3 балла — 0 ошибок; 2 балла — 1-3 ошибки; 1 балл — 4-5 ошибок; 0 баллов — 6+ ошибок.
- К9 (Грамматика): 3 балла — 0 ошибок; 2 балла — 1-2 ошибки; 1 балл — 3-4 ошибки; 0 баллов — 5+ ошибок.
- К10 (Речевые нормы): 3 балла — 0 ошибок; 2 балла — 1-2 ошибки; 1 балл — 3-4 ошибки; 0 баллов — 5+ ошибок.

Оформи ответ строго в формате Markdown по разделам:

### 1. Предварительный содержательный блок (К1–К3)
*(Оценивай логику на основе самого сочинения)*
* **К1 (Проблема):** Поставь балл (макс. 1).
* **К2 (Комментарий):** Поставь балл (макс. 3).
* **К3 (Позиция автора):** Поставь балл (макс. 2).

### 2. Речевое оформление и логика (К4–К6)
* **К4 (Обоснование позиции ученика):** Проверь наличие РЕАЛЬНОГО аргумента. Если его нет — обоснуй и поставь 0. Поставь балл (макс. 1).
* **К5 (Логика и абзацы):** Выпиши все вводные слова и проверь запятые вокруг них. Поставь балл (макс. 2).
* **К6 (Богатство речи):** Поставь балл (макс. 1).

### 3. Фактическая грамотность и детальный разбор ошибок (К7–К10)
СНАЧАЛА найди и выпиши ошибки, и только потом выставляй балл:
* **К7 (Орфография):** Итоговый балл: X/3.
* **К8 (Пунктуация):** Итоговый балл: X/3.
* **К9 (Грамматика):** Итоговый балл: X/3.
* **К10 (Речевые ошибки):** Итоговый балл: X/3.

*Формат вывода ошибок (если их нет, напиши «Ошибок не обнаружено»):*
- **Найдено в тексте:** «... [цитата] ...» -> **Исправлено:** «... [правильный вариант] ...» (Объяснение правила).

### 4. Итоговый строгий протокол баллов
* **К1:** X/1 | **К2:** X/3 | **К3:** X/2 | **К4:** X/1 | **К5:** X/2 | **К6:** X/1 | **К7:** X/3 | **К8:** X/3 | **К9:** X/3 | **К10:** X/3
* 📊 **Примерный общий балл:** X из 22.

### 5. Вердикт эксперта
Напиши 2-3 конкретные зоны роста. Если в сочинении отсутствуют ключевые элементы (например, аргумент в К4), прямо укажи на эту критическую ошибку.
"""

# ============================================================
#  ШАГ 2. ИНТЕРФЕЙС ВЕБ-САЙТА (Streamlit)
# ============================================================

st.title("📝 Помощник по проверке сочинений ЕГЭ")
st.caption("Индивидуальный проект за 10 класс")
st.markdown("🤖 **Нейросеть:** Яндекс Алиса AI (YandexGPT)")

st.markdown("---")

# Главная текстовая область
essay_text = st.text_area(
    "Сочинение:",
    height=300,
    placeholder="Вставьте или напишите текст сочинения здесь...",
)

# Кнопка запуска проверки
submit_button = st.button("🔍 Запустить автоматическую проверку", type="primary")

# ============================================================
#  ШАГ 3. ОТПРАВКА ЗАПРОСА В ЯНДЕКС AI STUDIO API
# ============================================================
if submit_button:
    cleaned_text = essay_text.strip()

    if not cleaned_text:
        st.warning("### ⚠️ Ошибка\nВы не ввели **текст сочинения**.")

    elif len(cleaned_text) < 50:
        st.warning(
            "### ⚠️ Ошибка\nТекст слишком короткий для полноценного анализа по критериям."
        )

    else:
        with st.spinner(
            "⏳ *Нейросеть Яндекс Алиса AI проводит подробный экспертный анализ по критериям 2027 года...*"
        ):
            try:
                url = "https://llm.api.cloud.yandex.net/v1/chat/completions"
                
                headers = {
                    "Content-Type": "application/json",
                    "Authorization": f"Api-Key {API_KEY}",
                }

                payload = {
                    "model": f"gpt://{FOLDER_ID}/yandexgpt/latest",
                    "messages": [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": cleaned_text},
                    ],
                    "temperature": 0.2,
                }

                response = requests.post(
                    url, headers=headers, data=json.dumps(payload), timeout=60
                )

                if response.status_code == 200:
                    data = response.json()
                    ai_response = data["choices"][0]["message"]["content"]

                    st.success("🎉 Проверка завершена!")
                    st.markdown("## ✅ Разбор сочинения выполнен!")
                    st.markdown("---")
                    st.markdown(ai_response)
                else:
                    st.error(
                        f"### ❌ Ошибка сервера API (Код {response.status_code})\n"
                        f"Текст ошибки: `{response.text}`"
                    )

            except Exception as e:
                st.error(
                    f"### ❌ Сетевая ошибка\n"
                    f"Не удалось связаться с сервером Яндекса.\n\n"
                    f"*Техническая информация:* `{e}`"
                )